import type { ThemeSkinTokenMap } from "./types.js";

/* 纯色板数据文件：与 i18n locale 同理按数据看待（.oxlintrc 对 locale 文件关闭
 * max-lines 的同一理由），这里就地豁免行数上限，避免把成对色板拆散到多个文件。 */
/* eslint-disable max-lines */
interface ModePalette {
  background: string;
  backgroundWinAlt: string;
  header: string;
  panel: string;
  sidebar: string;
  card: string;
  popover: string;
  popoverHeader: string;
  menu: string;
  menuHover: string;
  toast: string;
  tooltip: string;
  tooltipTag: string;
  tag: string;
  tab: string;
  tabActive: string;
  input: string;
  accent: string;
  brand: string;
  primary: string;
  primaryForeground: string;
  secondary: string;
  foreground: string;
  foregroundSubtle: string;
  foregroundSubtlest: string;
  foregroundInverse: string;
  border: string;
  borderHover: string;
  hover: string;
  selected: string;
  surface: string;
  surfaceHover: string;
}

function modeTokens(p: ModePalette): ThemeSkinTokenMap {
  return {
    "--color-background": p.background,
    "--color-background-win-alt": p.backgroundWinAlt,
    "--color-header": p.header,
    "--color-panel": p.panel,
    "--color-sidebar": p.sidebar,
    "--color-card": p.card,
    "--color-popover": p.popover,
    "--color-popover-header": p.popoverHeader,
    "--color-menu": p.menu,
    "--color-menu-hover": p.menuHover,
    "--color-toast": p.toast,
    "--color-tooltip": p.tooltip,
    "--color-tooltip-tag": p.tooltipTag,
    "--color-tag": p.tag,
    "--color-tab": p.tab,
    "--color-tab-active": p.tabActive,
    "--color-input": p.input,
    "--color-accent": p.accent,
    "--color-brand": p.brand,
    "--color-primary": p.primary,
    "--color-primary-foreground": p.primaryForeground,
    "--color-secondary": p.secondary,
    "--color-foreground": p.foreground,
    "--color-foreground-subtle": p.foregroundSubtle,
    "--color-foreground-subtlest": p.foregroundSubtlest,
    "--color-foreground-inverse": p.foregroundInverse,
    "--color-border": p.border,
    "--color-border-hover": p.borderHover,
    "--color-hover": p.hover,
    "--color-selected": p.selected,
    "--color-surface": p.surface,
    "--color-surface-hover": p.surfaceHover,
  };
}

